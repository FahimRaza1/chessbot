def evaluate(board: chess.Board) -> int:
    """Return a simple heuristic score from White's perspective."""
    if board.is_checkmate():
        return 100000 if board.turn == chess.BLACK else -100000

    score = 0
    for square, piece in board.piece_map().items():
        value = PIECE_VALUES[piece.piece_type]
        score += value if piece.color == chess.WHITE else -value

        table = PSQT[piece.piece_type]
        index = square
        if piece.color == chess.BLACK:
            index = chess.square_mirror(square)
        score += table[index] if piece.color == chess.WHITE else -table[index]

    # Small center control bonus.
    for square in chess.SquareSet(chess.BB_CENTER):
        piece = board.piece_at(square)
        if piece is not None:
            score += 3 if piece.color == chess.WHITE else -3

    return score
